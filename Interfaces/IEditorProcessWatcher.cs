namespace DocEditor.Interfaces;

/// <summary>
/// Стратегия отслеживания завершения работы внешнего редактора.
/// API спроектирован по принципу CQS: <see cref="IsRunning"/> — чистый запрос,
/// <see cref="Poll"/> — команда, продвигающая внутреннее состояние.
/// </summary>
internal interface IEditorProcessWatcher
{
  /// <summary>
  /// Возвращает признак, что редактор всё ещё считается работающим.
  /// Идемпотентный запрос, не имеет побочных эффектов.
  /// </summary>
  bool IsRunning { get; }

  /// <summary>
  /// Выполняет одну итерацию опроса состояния редактора.
  /// Может изменять внутреннее состояние и логировать результат проверки.
  /// </summary>
  void Poll();
}
